"use strict";
const test=require("node:test");
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const D=require("../dados.js");
function storage(){const m=new Map();return {getItem:k=>m.get(k)||null,setItem:(k,v)=>m.set(k,String(v))};}
test("uma ficha única cadastra prefeitura e vários papéis com um salvamento",()=>{
 const store=storage(),db=D.criar(store);
 const f=db.fichaPrefeitura();
 f.prefeitura={uf:"SC",nome:"Florianópolis",codigo_ibge:"4205407",telefone:"48999990000"};
 f.grupos.zonas.push({nome:"Centro",tipo:"Urbana"});
 f.grupos.usuarios.push({nome:"Ana",funcao:"responsavel",zona:"Centro"});
 f.grupos.usuarios.push({nome:"Bruno",funcao:"substituto",zona:"Centro"});
 f.grupos.usuarios.push({nome:"Celia",funcao:"coordenador",zona:"Centro"});
 f.grupos.instituicoes.push({nome:"Hospital",categoria:"Saúde",tipo:"Hospital"});
 const p=db.salvarFichaPrefeitura(f);
 assert.equal(db.municipioAtivo().id,p.id);
 assert.equal(db.lista("zonas").length,1);
 assert.equal(db.lista("responsaveis").length,1);
 assert.equal(db.lista("substitutos").length,1);
 assert.equal(db.lista("coordenadores").length,1);
 assert.equal(db.lista("saude").length,1);
 assert.equal(D.criar(store).fichaPrefeitura(p.id).grupos.usuarios.length,3);
});
test("edição da ficha preserva filhos e todas as coleções já existentes",()=>{
 const db=D.criar(storage());
 const representante=db.gravar("responsaveis",{nome:"Pessoa 1",zona:"Zona 7",telefone:"4412345678"});
 const equipe=db.gravar("equipes",{nome:"Brigada 1",zona:"Zona 7"});
 const canal=db.gravar("canais",{nome:"Central",tipo:"WhatsApp"});
 const colaborador=db.gravar("voluntarios",{nome:"Colaborador WhatsApp",tipo_pessoa:"FÍSICA",endereco:"Teste",telefone:"44999990000"});
 const pedido=db.gravar("solicitacoes",{nome:"Pessoa 2",tipo_pessoa:"FÍSICA",endereco:"Teste",telefone:"44999990001",necessidade:"Alimentação"});
 const ficha=db.fichaPrefeitura("maringa");
 ficha.prefeitura.email="defesa@prefeitura.example";
 ficha.grupos.usuarios[0].cargo="Coordenador operacional";
 ficha.grupos.zonas.push({nome:"Centro"});
 db.salvarFichaPrefeitura(ficha,"maringa");
 assert.equal(db.registro("responsaveis",representante.id).cargo,"Coordenador operacional");
 assert.equal(db.registro("equipes",equipe.id).nome,"Brigada 1");
 assert.equal(db.registro("canais",canal.id).nome,"Central");
 assert.equal(db.registro("voluntarios",colaborador.id).nome,"Colaborador WhatsApp");
 assert.equal(db.registro("solicitacoes",pedido.id).necessidade,"Alimentação");
 assert.equal(db.municipioAtivo().email,"defesa@prefeitura.example");
});
test("edição municipal não altera registros de outra prefeitura",()=>{
 const db=D.criar(storage());
 const f=db.fichaPrefeitura();
 f.prefeitura={uf:"SP",nome:"Cidade Teste",codigo_ibge:"3550308"};
 const p=db.salvarFichaPrefeitura(f);
 db.gravar("equipes",{nome:"Equipe SP"});
 db.selecionarMunicipio("maringa");
 db.gravar("equipes",{nome:"Equipe PR"});
 const pr=db.fichaPrefeitura("maringa");
 pr.grupos.equipes[0].tipo="Obras e infraestrutura";
 db.salvarFichaPrefeitura(pr,"maringa");
 db.selecionarMunicipio(p.id);
 assert.equal(db.lista("equipes").length,1);
 assert.equal(db.lista("equipes")[0].nome,"Equipe SP");
});
test("erro em dados da ficha não grava parte do cadastro",()=>{
 const db=D.criar(storage()),before=db.estado();
 const f=db.fichaPrefeitura();
 f.prefeitura.nome="Cidade Inválida";
 f.prefeitura.codigo_ibge="000";
 assert.throws(()=>db.salvarFichaPrefeitura(f),/IBGE/);
 assert.deepEqual(db.estado(),before);
});
